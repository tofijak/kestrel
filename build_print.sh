#!/bin/zsh
# Bygger STL'er, PrusaSlicer-projekter (.3mf med indstillinger) og G-code til Prusa MINI.
# Brug:  ./build_print.sh /sti/til/python [PLA|PETG]   (python med manifold3d + trimesh)
#        IRON=1 ./build_print.sh ...  slår ironing til (glat top på MagSafe-puden, +25 min).
#        Standard er fra, så testprint af pasformen går hurtigere.
set -e
cd "$(dirname "$0")"
PY=${1:-python3}
MAT=${2:-PETG}
case $MAT in
  PLA)  MATERIAL="Esun PLA - Copy"; MATOPT=(--temperature 195) ;;   # 5 °C lavere mod tråde
  PETG) MATERIAL="Generic PETG @MINIIS - Copy"; MATOPT=() ;;
  *) echo "ukendt materiale: $MAT"; exit 1 ;;
esac
if [[ ${IRON:-0} == 1 ]]; then IRONOPT=(--ironing --ironing-type topmost); else IRONOPT=(--no-ironing); fi
PS="/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer"
TMP=$(mktemp -d)
mkdir -p print

$PY digiscope.py
$PY oneplus13_model.py

P=(--loglevel 1
   --printer-profile "Original Prusa MINI & MINI+ Input Shaper - Copy"
   --print-profile "0.20mm STRUCTURAL @MINIIS 0.4"
   --material-profile "$MATERIAL"
   --perimeters 4 --top-solid-layers 6 --bottom-solid-layers 5
   --fill-density 30% --fill-pattern gyroid --dont-arrange
   # Overfladekvalitet (efter første print: lodret søm, tråde over magnetlommer, knopper på toppen)
   --seam-position rear --scarf-seam-placement everywhere --scarf-seam-only-on-smooth  # skrå søm: ingen lodret linje
   --avoid-crossing-perimeters      # kør inden i delen, ikke hen over magnetlommerne -> ingen tråde/knopper
   --retract-length 3.2 --retract-speed 35 --wipe   # MINI-bowden: Prusas standard 3,2 mm + wipe ved sømmen
   "${IRONOPT[@]}"                 # ironing: IRON=1 (kun øverste lag: +25 min i stedet for +1 t 45)
   "${MATOPT[@]}")

"$PS" "${P[@]}" --save "$TMP/config.ini" okular_ring_ATX.stl >/dev/null
sed -i '' 's/^support_material = 1$/support_material = 0/' "$TMP/config.ini"
cp "$TMP/config.ini" print/digiscope_${MAT}_MINI.ini

build() {  # navn del1.stl del2.stl
  local name=$1; shift
  $PY make_plate.py "$TMP/$name.3mf" "$@"
  "$PS" "${P[@]}" --export-3mf -o "print/$name.3mf" "$TMP/$name.3mf" >/dev/null
  $PY - "print/$name.3mf" "$TMP/config.ini" <<'EOF'
import os, sys, zipfile
f, cfg = sys.argv[1], open(sys.argv[2]).read().splitlines()
body = "; generated by PrusaSlicer 2.9.7\n\n" + "\n".join(
    "; " + l for l in cfg if l.strip() and not l.startswith("#")) + "\n"
with zipfile.ZipFile(f) as zi, zipfile.ZipFile(f + ".tmp", "w", zipfile.ZIP_DEFLATED) as zo:
    for it in zi.infolist():
        zo.writestr(it, zi.read(it.filename))
    zo.writestr("Metadata/Slic3r_PE.config", body)
os.replace(f + ".tmp", f)
EOF
  "$PS" --loglevel 2 --load print/digiscope_${MAT}_MINI.ini --dont-arrange \
        --export-gcode -o "print/$name.bgcode" "print/$name.3mf" 2>&1 | grep -iE "warning|issue|^[A-Za-z_]+[0-9]*$|bridg|loose|float" || true
  echo "OK: print/$name.3mf + .bgcode"
}

build ${MAT}_ATX_OnePlus13 okular_ring_ATX.stl telefon_adapter_OP13.stl
build ${MAT}_Diamondback_iPhone15 okular_ring_DiamondbackHD85.stl telefon_adapter_iPhone15.stl
build ${MAT}_kun_ring_ATX okular_ring_ATX.stl
rm -rf "$TMP"
